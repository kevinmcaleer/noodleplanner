#!/usr/bin/env python3
"""Benchmark the server-side cost of parsing a plan.

Background: issue #788 ("Browser-first architecture") rests on how much CPU the
Raspberry Pi backend spends on ``POST /api/parse``, which the frontend calls on
essentially every plan change. This harness produces the numbers that justify
that work, and can be re-run after each phase to show the cost coming down.

It reports three things per plan size:

* ``parse ms``     -- ``PlanService.parse()`` alone, the pure computation.
* ``no-ascii ms``  -- the same call with ``text_to_markdown_table()`` stubbed
  out. ``/api/parse`` returns an ``ascii_output`` string that only the
  ``/render`` path consumes, so this sizes the Phase 0 saving.
* ``HTTP ms``      -- the full endpoint via ``TestClient``, which adds request
  validation and JSON encoding of every task row.

Plans are generated by repeating a fixed block of 11 leaf tasks across 6 phases,
with names suffixed per copy so ``[depends ...]`` references stay unambiguous.
Ten repeats therefore gives 110 leaf tasks, matching the sizes quoted in #788.

Usage::

    python scripts/benchmark_parse.py                    # 110/275/550/1100 tasks
    python scripts/benchmark_parse.py --repeats 10 100   # custom sizes
    python scripts/benchmark_parse.py --markdown         # paste into an issue
    python scripts/benchmark_parse.py --no-http          # skip the endpoint pass

Run it from the repo root with the project venv, e.g. ``uv run
scripts/benchmark_parse.py``.
"""

from __future__ import annotations

import argparse
import logging
import platform
import statistics
import sys
import time
from dataclasses import dataclass

from noodle_web import plan_service as plan_service_module
from noodle_web.plan_service import PlanService

# Leaf tasks per repeated block, used to label results in the same units as #788.
TASKS_PER_BLOCK = 11

FRONT_MATTER = """---
title: Benchmark Project
project manager: Kevin
Resources:
- @Andy: Andy Mcarthy, Lead Developer
- @Bob: Bob Smith, Developer, 50%
- @Charlie: Charlie Brown, QA Engineer
- @Diana: Diana Prince, Product Owner
- @Frank: Frank Castle, DevOps Engineer
- @Eve: Eve Adams, Project Coordinator

Holidays:
- 2025-12-25
- 2025-12-26
---

Project
"""

BLOCK = """  Requirements {i}
    capture requirements {i} @Andy 3days 50% "Interviews with stakeholders" 2025-10-01
  Design {i}
    Low Level Design {i} @Andy 2days [depends capture requirements {i}] "with signoff"
  Build {i}
    develop software {i} @Bob 5days [depends Low Level Design {i}] "agile development"
  Test {i}
    test plan {i} @Charlie 3days [depends develop software {i}]
    * system testing {i} @Charlie @Andy 4days
    * user acceptance testing {i} @Diana 2days
    * Testing Complete {i} 0d
  Deploy {i}
    go-no-go decision {i} @Eve 1day [depends user acceptance testing {i}]
    * go live {i} @Frank 1day "final decision"
    * Deploy Complete {i} 0d "product now live"
  Support {i}
    hypercare {i} @Andy 7days [depends go live {i}] "24/7 support provided for 1 week"
"""


@dataclass
class Row:
    """One plan size's worth of timings, all medians in milliseconds."""

    repeats: int
    leaf_tasks: int
    rows: int
    parse: float
    parse_stdev: float
    no_ascii: float
    http: float | None

    @property
    def ascii_saving_pct(self) -> float:
        return 100 * (self.parse - self.no_ascii) / self.parse


def make_plan(repeats: int) -> str:
    """Build a plan containing ``repeats`` copies of the task block."""
    return FRONT_MATTER + "".join(
        BLOCK.format(i=i) for i in range(1, repeats + 1)
    )


def time_calls(fn, plan: str, runs: int, warmup: int = 1) -> list[float]:
    """Return ``runs`` timings of ``fn(plan)`` in ms, after discarding warm-ups."""
    for _ in range(warmup):
        fn(plan)

    samples = []
    for _ in range(runs):
        started = time.perf_counter()
        fn(plan)
        samples.append((time.perf_counter() - started) * 1000)
    return samples


def make_http_caller():
    """Return a callable that posts a plan to /api/parse via TestClient."""
    from fastapi.testclient import TestClient

    from noodle_web.app import app
    from noodle_web.security import reset_rate_limit_store

    client = TestClient(app)

    def call(plan: str) -> None:
        # The app rate-limits to 100 requests per minute per IP, which a long
        # run would trip. Clearing the store costs a fraction of a microsecond
        # against a measurement in the tens of milliseconds.
        reset_rate_limit_store()

        response = client.post("/api/parse", json={"plan_text": plan})
        if response.status_code != 200:
            raise RuntimeError(f"/api/parse returned {response.status_code}")

    return call


def measure(repeats: int, runs: int, http_caller) -> Row:
    """Time every variant for a plan of ``repeats`` blocks."""
    service = PlanService()
    plan = make_plan(repeats)

    result = service.parse(plan)
    if not result.success:
        raise RuntimeError(f"parse failed at {repeats} repeats: {result.error}")

    full = time_calls(service.parse, plan, runs)

    # Stub the ascii table so we can price the part of the response that
    # /api/parse callers throw away. Restored even if parsing blows up.
    real_table = plan_service_module.text_to_markdown_table
    plan_service_module.text_to_markdown_table = lambda *args, **kwargs: ""
    try:
        lean = time_calls(service.parse, plan, runs)
    finally:
        plan_service_module.text_to_markdown_table = real_table

    http = None
    if http_caller is not None:
        http = statistics.median(time_calls(http_caller, plan, runs))

    return Row(
        repeats=repeats,
        leaf_tasks=repeats * TASKS_PER_BLOCK,
        rows=len(result.tasks),
        parse=statistics.median(full),
        parse_stdev=statistics.stdev(full) if len(full) > 1 else 0.0,
        no_ascii=statistics.median(lean),
        http=http,
    )


def describe_machine() -> str:
    """One line identifying what the numbers were measured on."""
    model = ""
    try:
        with open("/proc/device-tree/model", "rb") as handle:
            model = handle.read().decode().strip("\x00").strip()
    except OSError:
        model = platform.processor() or platform.machine()

    return (
        f"{model} | {platform.machine()} | Python {platform.python_version()} "
        f"| {platform.node()}"
    )


def print_table(rows: list[Row], markdown: bool) -> None:
    """Render results as an aligned text table, or as Markdown for an issue."""
    show_http = any(row.http is not None for row in rows)

    headers = ["tasks", "rows", "parse ms", "stdev", "no-ascii ms", "saving"]
    if show_http:
        headers.append("HTTP ms")

    cells = []
    for row in rows:
        cell = [
            str(row.leaf_tasks),
            str(row.rows),
            f"{row.parse:.1f}",
            f"{row.parse_stdev:.1f}",
            f"{row.no_ascii:.1f}",
            f"{row.ascii_saving_pct:.1f}%",
        ]
        if show_http:
            cell.append(f"{row.http:.1f}" if row.http is not None else "-")
        cells.append(cell)

    if markdown:
        print("| " + " | ".join(headers) + " |")
        print("|" + "|".join(["---:"] * len(headers)) + "|")
        for cell in cells:
            print("| " + " | ".join(cell) + " |")
        return

    widths = [
        max(len(headers[i]), max(len(cell[i]) for cell in cells))
        for i in range(len(headers))
    ]
    line = "  ".join(headers[i].rjust(widths[i]) for i in range(len(headers)))
    print(line)
    print("-" * len(line))
    for cell in cells:
        print("  ".join(cell[i].rjust(widths[i]) for i in range(len(headers))))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--repeats",
        type=int,
        nargs="+",
        default=[10, 25, 50, 100],
        metavar="N",
        help=f"plan sizes, in blocks of {TASKS_PER_BLOCK} leaf tasks "
        "(default: 10 25 50 100)",
    )
    parser.add_argument(
        "--runs",
        type=int,
        default=15,
        help="timed runs per measurement, after a warm-up (default: 15)",
    )
    parser.add_argument(
        "--markdown",
        action="store_true",
        help="emit a Markdown table, for pasting into an issue",
    )
    parser.add_argument(
        "--no-http",
        action="store_true",
        help="skip the full-endpoint pass (parse timings only)",
    )
    args = parser.parse_args(argv)

    # The service logs an INFO line per parse, which would swamp the results.
    logging.disable(logging.CRITICAL)

    http_caller = None if args.no_http else make_http_caller()

    print(describe_machine())
    print(f"median of {args.runs} runs, 1 warm-up discarded")
    print()

    rows = [
        measure(repeats, args.runs, http_caller)
        for repeats in sorted(args.repeats)
    ]
    print_table(rows, args.markdown)
    return 0


if __name__ == "__main__":
    sys.exit(main())
